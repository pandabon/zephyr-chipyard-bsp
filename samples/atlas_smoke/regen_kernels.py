"""Regenerate kernels/*.bin and src/kernels_gen.h from kernels/*.S.

Runs the Atlas team's assembler (not vendored here):

    ATLAS_NPU_DIR=/path/to/generators/atlas-npu ./regen_kernels.py

ATLAS_NPU_DIR defaults to $BRINGUP_CHIPYARD/generators/atlas-npu. The .bin output is raw
little-endian 32-bit words, entry = word 0 (assembler.py --out-bin). A kernel may contain
"# @RAWWORD <index> <value>" to overwrite one assembled word, e.g. with an illegal instruction.
"""
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_BRINGUP = os.environ.get("BRINGUP_CHIPYARD")
DEFAULT = os.path.join(_BRINGUP, "generators/atlas-npu") if _BRINGUP else None
KERNELS = ["k_ecall", "k_vmem", "k_illegal"]


def main():
    npu = os.environ.get("ATLAS_NPU_DIR", DEFAULT)
    if not npu:
        sys.exit("set ATLAS_NPU_DIR=<bringup-chipyard>/generators/atlas-npu "
                 "(or export BRINGUP_CHIPYARD=<your bringup-chipyard checkout>)")
    asm = os.path.join(npu, "baremetal", "assembler.py")
    if not os.path.isfile(asm):
        sys.exit("assembler not found: %s (set ATLAS_NPU_DIR)" % asm)
    hdr = ["/* GENERATED by regen_kernels.py from kernels/*.S - do not edit.",
           " * Raw Atlas IMEM images: little-endian 32-bit words, entry = word 0. */", ""]
    for k in KERNELS:
        src = os.path.join(HERE, "kernels", k + ".S")
        out = os.path.join(HERE, "kernels", k + ".bin")
        subprocess.run([sys.executable, "-B", asm, src, "--out-bin", out], check=True)
        words = list(struct.unpack("<%dI" % (os.path.getsize(out) // 4), open(out, "rb").read()))
        for m in re.finditer(r"^#\s*@RAWWORD\s+(\d+)\s+(\S+)", open(src).read(), re.M):
            words[int(m.group(1))] = int(m.group(2), 0) & 0xFFFFFFFF
        with open(out, "wb") as f:
            f.write(struct.pack("<%dI" % len(words), *words))
        hdr.append("static const uint32_t %s_words[] = {" % k)
        hdr += ["\t0x%08x," % w for w in words]
        hdr += ["};", ""]
        print("%s: %d words" % (k, len(words)))
    with open(os.path.join(HERE, "src", "kernels_gen.h"), "w") as f:
        f.write("\n".join(hdr))


if __name__ == "__main__":
    main()
